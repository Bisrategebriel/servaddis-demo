import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

// File storage seam (TRD §2). The demo writes to local disk, outside public/, so files are only
// reachable through the authorized /api/files endpoint. Production swaps in object storage
// behind the same interface.

export interface StorageAdapter {
  save(bytes: Uint8Array, ext: string): Promise<string>;
  read(key: string): Promise<Uint8Array | null>;
  remove(key: string): Promise<void>;
}

const KEY = /^[0-9a-f-]{36}\.[a-z0-9]{1,5}$/;
const uploadDir = () =>
  path.resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_DIR ?? "./data/uploads");

/** Keys are generated by save(), so anything else (e.g. "../.env") is never a valid path. */
const keyPath = (key: string) =>
  KEY.test(key) ? path.join(/*turbopackIgnore: true*/ uploadDir(), key) : null;

export const storage: StorageAdapter = {
  async save(bytes, ext) {
    const key = `${randomUUID()}.${ext}`;
    const dir = uploadDir();
    await mkdir(/*turbopackIgnore: true*/ dir, { recursive: true });
    await writeFile(path.join(/*turbopackIgnore: true*/ dir, key), bytes);
    return key;
  },
  async read(key) {
    const file = keyPath(key);
    if (!file) return null;
    return readFile(file).catch(() => null);
  },
  async remove(key) {
    const file = keyPath(key);
    if (file) await rm(file, { force: true });
  },
};
